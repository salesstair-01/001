package sqlengine

import (
	"context"
	"testing"
)

// TestTemporalFunctions pins issue #25's functions and numeric datetimes
// against MySQL 8.0.46's results for the same statements.
func TestTemporalFunctions(t *testing.T) {
	c := startCluster(t)
	conn, err := c.db(t).Conn(context.Background())
	if err != nil {
		t.Fatal(err)
	}
	defer conn.Close()
	for _, s := range []struct{ q, want string }{
		{"SELECT ADDTIME('2007-12-31 23:59:59.999999', '1 1:1:1.000002')", "[2008-01-02 01:01:01.000001]"},
		{"SELECT ADDTIME('01:00:00.999999', '02:00:00.999998')", "[03:00:01.999997]"},
		{"SELECT SUBTIME('2007-12-31 23:59:59.999999','1 1:1:1.000002')", "[2007-12-30 22:58:58.999997]"},
		{"SELECT SUBTIME('01:00:00.999999', '02:00:00.999998')", "[-00:59:59.999999]"},
		{"SELECT ADDTIME('01:00:00','02:00:00'), ADDTIME('01:00:00.5','1'), ADDTIME('2001-01-01 00:00:00','1'), ADDTIME('01:00:00', 1.5), ADDTIME('839:00:00','1')",
			"[03:00:00,01:00:01.500000,2001-01-01 00:00:01,01:00:01.500000,838:59:59]"},
		{"SELECT ADDTIME('2001-01-01','1'), ADDTIME('x','1'), ADDTIME('01:00:00', '2001-01-01 00:00:00'), ADDTIME('-1:00:00','00:30:00'), ADDTIME('1 2:00:00','1'), ADDTIME(NULL, '1')",
			"[838:59:59,NULL,NULL,-00:30:00,26:00:01,NULL]"},
		{"SELECT ADDTIME(DATE'2001-01-01','01:00:00'), ADDTIME(TIMESTAMP'2001-01-01 23:00:00','01:00:00')", "[2001-01-01 01:00:00,2001-01-02 00:00:00]"},
		{"SELECT TIMEDIFF('2000:01:01 00:00:00', '2000:01:01 00:00:00.000001'), TIMEDIFF('10:00:00','2001-01-01 00:00:00'), TIMEDIFF('2001-01-02','2001-01-01')",
			"[-00:00:00.000001,NULL,00:00:00]"},
		{"SELECT TIME_TO_SEC('22:23:00'), TIME_TO_SEC('-01:00:00'), TIME_TO_SEC('1 01:00:00'), TIME_TO_SEC('10:00:00.5'), TIME_TO_SEC('2001-01-01 10:00:00')",
			"[80580,-3600,90000,36000,36000]"},
		{"SELECT SEC_TO_TIME(2378), SEC_TO_TIME(-1), SEC_TO_TIME(2378.5), SEC_TO_TIME(3600*900), SEC_TO_TIME(1.25), SEC_TO_TIME('100'), SEC_TO_TIME(-3020399), SEC_TO_TIME('abc'), SEC_TO_TIME(1e3)",
			"[00:39:38,-00:00:01,00:39:38.5,838:59:59,00:00:01.25,00:01:40.000000,-838:59:59,00:00:00.000000,00:16:40.000000]"},
		{"SELECT MAKETIME(12,15,30), MAKETIME(-1,2,3), MAKETIME(1,60,0), MAKETIME(1,2,3.5), MAKETIME(1,2,'3.25'), MAKETIME(900,0,0), MAKETIME(1,-1,0), MAKETIME(1,0,60), MAKETIME(1,0,59.9999999), MAKETIME(1.6,2.4,3)",
			"[12:15:30,-01:02:03,NULL,01:02:03.5,01:02:03.250000,838:59:59,NULL,NULL,01:01:00.000000,02:02:03]"},
		{"SELECT CONCAT(MAKEDATE(2011,31)), CONCAT(MAKEDATE(2011,400)), MAKEDATE(2014,0), CONCAT(MAKEDATE(69,1)), CONCAT(MAKEDATE(99,1)), CONCAT(MAKEDATE(100,1)), MAKEDATE(9999,366), CONCAT(MAKEDATE(2011,1.5))",
			"[2011-01-31,2012-02-04,NULL,2069-01-01,1999-01-01,0100-01-01,NULL,2011-01-02]"},
		{"SELECT PERIOD_ADD(200801,2), PERIOD_ADD(0801,2), PERIOD_ADD(9912, 1), PERIOD_ADD(6912,1), PERIOD_ADD(200801,-2), PERIOD_ADD('200801',1), PERIOD_ADD(200801,1.6)",
			"[200803,200803,200001,207001,200711,200802,200803]"},
		{"SELECT PERIOD_DIFF(200802,200703), PERIOD_DIFF(0802, 0703), PERIOD_DIFF(1,1)", "[11,11,0]"},
		{"SELECT PERIOD_ADD(200813,1)", "ERR 1210"},
		{"SELECT PERIOD_DIFF(200801,0)", "ERR 1210"},
		{"SELECT UTC_DATE() = DATE(UTC_TIMESTAMP()), LENGTH(UTC_TIME()), LENGTH(UTC_TIME(3))", "[1,8,12]"},
		{"SELECT UTC_TIME(7)", "ERR 1426"},

		// numeric datetimes
		{"CREATE TABLE nd (id int PRIMARY KEY, a datetime, b timestamp NULL, c date)", "[]"},
		{"INSERT INTO nd VALUES (1, 20010202105916, 20010202105916, 20010202)", "[]"},
		{"INSERT INTO nd VALUES (2, 010202105916, '010202105916', '20010202')", "[]"},
		{"INSERT INTO nd VALUES (3, 20010202, 20010202, 20010202105916)", "[]"},
		{"INSERT INTO nd VALUES (4, 20010202105916.5, NULL, NULL)", "[]"},
		{"INSERT INTO nd VALUES (5, 99999999999999, NULL, NULL)", "ERR 1292"},
		{"INSERT INTO nd VALUES (5, 20011301, NULL, NULL)", "ERR 1292"},
		{"INSERT INTO nd SELECT 5, 20050505, NULL, NULL", "[]"},
		{"SELECT id, CONCAT(a), CONCAT(b), c FROM nd ORDER BY id",
			"[1,2001-02-02 10:59:16,2001-02-02 10:59:16,2001-02-02T00:00:00Z 2,2001-02-02 10:59:16,2001-02-02 10:59:16,2001-02-02T00:00:00Z 3,2001-02-02 00:00:00,2001-02-02 00:00:00,2001-02-02T00:00:00Z 4,2001-02-02 10:59:17,NULL,NULL 5,2005-05-05 00:00:00,NULL,NULL]"},
		{"SELECT id FROM nd WHERE a = 20010202105916 ORDER BY id", "[1 2]"},
		{"SELECT id FROM nd WHERE a BETWEEN 20050101 AND 20991231", "[5]"},
		{"UPDATE nd SET a = 20030303000000 WHERE id = 1", "[]"},
		{"UPDATE nd SET c = 20040404 WHERE a > 20030101", "[]"},
		{"SELECT CONCAT(a), c FROM nd WHERE id = 1", "[2003-03-03 00:00:00,2004-04-04T00:00:00Z]"},
		{"SELECT CONCAT(CAST(20010202105916 AS DATETIME)), CAST(20010202 AS DATE), CONCAT(CAST('010202105916' AS DATETIME))",
			"[2001-02-02 10:59:16,2001-02-02T00:00:00Z,2001-02-02 10:59:16]"},
	} {
		if got := connRun(t, conn, s.q); got != s.want {
			t.Errorf("%s: got %s, want %s", s.q, got, s.want)
		}
	}
}
